const warned = new Set();

export default function Icon({ name, size = 24, color = '#2f2d29', strokeWidth = 1.8, style }) {
  const Glyph = ICONS[name];

  if (!Glyph && __DEV__ && !warned.has(name)) {
    warned.add(name);
    console.warn(`Icon "${name}" is not in components/Icon.js. Add it to ICONS.`);
  }

  const Shown = Glyph || Circle;
  return <Shown size={size} color={color} strokeWidth={strokeWidth} style={style} />;
}